package native

import (
	"fmt"
	"time"
)

// tr translates interface chrome. User content and backend errors stay in
// their original language.
func (a *App) tr(text string) string {
	if a.language != "zh" {
		return text
	}
	if translated, ok := zhCN[text]; ok {
		return translated
	}
	return text
}

func (a *App) trf(format string, args ...any) string {
	return fmt.Sprintf(a.tr(format), args...)
}

func (a *App) dateTime(at time.Time) string {
	if a.language == "zh" {
		return at.Local().Format("1月2日 15:04")
	}
	return at.Local().Format("Jan 2, 15:04")
}

func (a *App) date(at time.Time) string {
	if a.language == "zh" {
		return at.Local().Format("1月2日")
	}
	return at.Local().Format("Jan 2")
}

